const Midi_Program_Ex *Midi_Db::find_ex(unsigned msb, unsigned lsb, unsigned pgm) const
{
    // midi_ex_id() drops the percussion bit, which would give a percussion
    // key the name of the melodic program with the same number.
    if (pgm > 127)
        return nullptr;
    const auto it = midi_ex_.find(midi_ex_id(msb, lsb, pgm));
    return (it != midi_ex_.end()) ? &it->second : nullptr;
}
