const char *midi_spec_name(Midi_Spec spec)
{
    switch (spec) {
    case Midi_Spec::GM: return "GM";
    case Midi_Spec::GS: return "GS";
    case Midi_Spec::SC88: return "SC88";
    case Midi_Spec::MT32: return "MT32";
    case Midi_Spec::XG: return "XG";
    }
    return nullptr;
}

